const DICTS: Record<LocaleCode, PartialDict> = { en, ta, hi }

/* ------------------------------------------------------------------ */
/* Store                                                              */
/* ------------------------------------------------------------------ */
type I18nState = {
  locale: LocaleCode
  setLocale: (l: LocaleCode) => void
}

export const useI18nStore = create<I18nState>()(
  persist(
    (set) => ({
      locale: DEFAULT_LOCALE,
      setLocale: (locale) => set({ locale }),
    }),
    { name: 'lms-locale' }
  )
)

export function translate(locale: LocaleCode, key: DictKey, vars?: Record<string, string | number>): string {
  const dict = DICTS[locale] ?? {}
  let str = dict[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return str
}

/** Main hook: const { t, locale, setLocale } = useI18n() */
export function useI18n() {
  const locale = useI18nStore((s) => s.locale)
  const setLocale = useI18nStore((s) => s.setLocale)
  const t = (key: DictKey, vars?: Record<string, string | number>) => translate(locale, key, vars)
  return { t, locale, setLocale }
}
